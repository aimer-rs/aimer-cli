//! The WiX source of a Windows Installer package.
//!
//! The source is written for the WiX Toolset v4 and later (`wix build`; the
//! `http://wixtoolset.org/schemas/v4/wxs` schema). It installs the bundle
//! per machine under `Program Files`, one component per file, adds a Start menu
//! shortcut, and an upgrade code that is stable across builds so that a newer
//! package replaces an installed one (`MajorUpgrade`).
//!
//! Ids are numbered (`D1`, `C1`, `F1`, ...): file names are not valid Windows
//! Installer identifiers.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, bail};

/// What the source is generated from.
pub(super) struct Installer<'a> {
    pub app_name: &'a str,
    /// The executable inside the bundle.
    pub exe_name: &'a str,
    pub version: &'a str,
    pub publisher: &'a str,
    /// The bundle to install, as an absolute path.
    pub bundle: &'a Path,
    /// The stable GUID that identifies the product family across versions.
    pub upgrade_code: &'a str,
}

/// `wix build` of `source` into `output` for `arch` (`x64`, `arm64`, `x86`).
///
/// `-pdbtype none` keeps a `.wixpdb` from being left next to the package.
pub(super) fn command(wix: &Path, source: &Path, output: &Path, arch: &str) -> Command {
    let mut cmd = Command::new(wix);
    cmd.arg("build")
        .args(["-arch", arch])
        .args(["-pdbtype", "none"])
        .arg("-o")
        .arg(output)
        .arg(source);
    cmd
}

/// The `Version` of an MSI: `major.minor.build`, which Windows Installer limits
/// to 255, 255 and 65535. A suffix such as `-beta` is dropped (the installer
/// ignores a fourth part and a suffix when it compares versions), and no version
/// at all is `1.0.0`.
///
/// # Errors
///
/// Fails when the version is not made of numbers, or a part is too large, since
/// the installer would reject or misorder it.
pub(super) fn msi_version(version: &str) -> anyhow::Result<String> {
    let version = version.trim();
    if version.is_empty() {
        return Ok("1.0.0".to_string());
    }
    let numbers = version.split(['-', '+']).next().unwrap_or(version);
    let limits = [255u32, 255, 65_535];
    let mut parts = [0u32; 3];
    for (index, part) in numbers.split('.').enumerate() {
        let Some(slot) = parts.get_mut(index) else {
            bail!(
                "version '{version}' has more than three parts; an MSI version is major.minor.build"
            );
        };
        *slot = part
            .parse()
            .ok()
            .filter(|n| *n <= limits[index])
            .with_context(|| {
                format!(
                    "version '{version}' does not fit an MSI version \
                     (major.minor.build, up to 255.255.65535)"
                )
            })?;
    }
    Ok(format!("{}.{}.{}", parts[0], parts[1], parts[2]))
}

/// The source text.
///
/// # Errors
///
/// Fails when the bundle cannot be read or the version does not fit an MSI.
pub(super) fn source(installer: &Installer) -> anyhow::Result<String> {
    let version = msi_version(installer.version)?;
    let publisher = if installer.publisher.trim().is_empty() {
        installer.app_name
    } else {
        installer.publisher.trim()
    };

    let mut tree = Tree::default();
    tree.directory(installer.bundle, 2)?;

    let icon = installer.bundle.join("app.ico");
    let mut icon_lines = String::new();
    if icon.is_file() {
        let _ = writeln!(
            icon_lines,
            "    <Icon Id=\"AppIcon.ico\" SourceFile=\"{}\" />\n    \
             <Property Id=\"ARPPRODUCTICON\" Value=\"AppIcon.ico\" />",
            attr(&icon.to_string_lossy())
        );
    }

    let refs: String = tree
        .components
        .iter()
        .map(|id| format!("      <ComponentRef Id=\"{id}\" />\n"))
        .collect();
    Ok(format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!-- Generated by `aimer package windows`; edits are lost on the next run. -->\n\
         <Wix xmlns=\"http://wixtoolset.org/schemas/v4/wxs\">\n  \
         <Package Name=\"{name}\" Manufacturer=\"{publisher}\" Version=\"{version}\" \
         UpgradeCode=\"{upgrade}\" Scope=\"perMachine\">\n    \
         <MajorUpgrade DowngradeErrorMessage=\"A newer version of [ProductName] is already installed.\" />\n    \
         <MediaTemplate EmbedCab=\"yes\" />\n\
         {icon_lines}\n    \
         <StandardDirectory Id=\"ProgramFiles64Folder\">\n      \
         <Directory Id=\"INSTALLFOLDER\" Name=\"{folder}\">\n\
         {files}      </Directory>\n    \
         </StandardDirectory>\n\n    \
         <StandardDirectory Id=\"ProgramMenuFolder\">\n      \
         <Directory Id=\"ApplicationProgramsFolder\" Name=\"{folder}\">\n        \
         <Component Id=\"StartMenuShortcut\">\n          \
         <Shortcut Id=\"AppShortcut\" Name=\"{name}\" Target=\"[INSTALLFOLDER]{exe}\" \
         WorkingDirectory=\"INSTALLFOLDER\" />\n          \
         <RemoveFolder Id=\"RemoveProgramsFolder\" On=\"uninstall\" />\n          \
         <RegistryValue Root=\"HKCU\" Key=\"Software\\{folder}\" Name=\"installed\" \
         Type=\"integer\" Value=\"1\" KeyPath=\"yes\" />\n        \
         </Component>\n      \
         </Directory>\n    \
         </StandardDirectory>\n\n    \
         <Feature Id=\"Main\" Title=\"{name}\" Level=\"1\">\n\
         {refs}      <ComponentRef Id=\"StartMenuShortcut\" />\n    \
         </Feature>\n  \
         </Package>\n\
         </Wix>\n",
        name = attr(installer.app_name),
        publisher = attr(publisher),
        upgrade = installer.upgrade_code,
        folder = attr(&folder_name(installer.app_name)),
        exe = attr(installer.exe_name),
        files = tree.xml,
    ))
}

/// The directories and components of the bundle, as WiX elements.
#[derive(Default)]
struct Tree {
    xml: String,
    /// The id of every component, for the feature that installs them.
    components: Vec<String>,
    directories: u32,
    files: u32,
}

impl Tree {
    /// Write the files of `dir` as components, and its folders as nested
    /// directories, depth first and in name order.
    fn directory(&mut self, dir: &Path, depth: usize) -> anyhow::Result<()> {
        let mut children: Vec<PathBuf> = std::fs::read_dir(dir)
            .with_context(|| format!("reading {}", dir.display()))?
            .map(|entry| entry.map(|e| e.path()))
            .collect::<Result<_, _>>()?;
        children.sort();
        let pad = "  ".repeat(depth + 2);

        for path in children {
            let name = path
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            if path.is_dir() {
                self.directories += 1;
                let id = format!("D{}", self.directories);
                let _ = writeln!(
                    self.xml,
                    "{pad}<Directory Id=\"{id}\" Name=\"{}\">",
                    attr(&name)
                );
                self.directory(&path, depth + 1)?;
                let _ = writeln!(self.xml, "{pad}</Directory>");
            } else {
                self.files += 1;
                let component = format!("C{}", self.files);
                let _ = writeln!(
                    self.xml,
                    "{pad}<Component Id=\"{component}\">\n{pad}  <File Id=\"F{}\" Source=\"{}\" KeyPath=\"yes\" />\n{pad}</Component>",
                    self.files,
                    attr(&path.to_string_lossy()),
                );
                self.components.push(component);
            }
        }
        Ok(())
    }
}

/// Text for an XML attribute value.
fn attr(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// The application name as a folder name: the characters Windows forbids in one
/// are dropped.
fn folder_name(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .filter(|c| !matches!(c, '\\' | '/' | ':' | '*' | '?' | '"' | '<' | '>' | '|'))
        .collect();
    let cleaned = cleaned.trim().trim_end_matches('.').to_string();
    if cleaned.is_empty() {
        "App".to_string()
    } else {
        cleaned
    }
}

