//! The Inno Setup script of a Windows setup program.
//!
//! The script installs per user by default (`PrivilegesRequired=lowest`, so no
//! administrator prompt) and lets the user pick an all-users install in a
//! dialog; `{autopf}` follows that choice. It adds a Start menu entry, an
//! optional desktop shortcut, an uninstaller and a "launch" checkbox on the last
//! page. `AppId` is stable, so a newer setup upgrades an installed copy.
//!
//! `ArchitecturesAllowed=x64compatible` needs Inno Setup 6.3 or later.

use std::path::Path;
use std::process::Command;

/// What the script is generated from.
pub(super) struct Installer<'a> {
    pub app_name: &'a str,
    /// The executable inside the bundle.
    pub exe_name: &'a str,
    pub version: &'a str,
    pub publisher: &'a str,
    /// The bundle to install, as an absolute path.
    pub bundle: &'a Path,
    /// Where the setup program is written, as an absolute path.
    pub dist: &'a Path,
    /// The setup program's file name, without `.exe`.
    pub base_name: &'a str,
    /// The stable GUID that identifies the app to Windows.
    pub app_id: &'a str,
    /// `x64`, `arm64` or `x86`.
    pub arch: &'a str,
}

/// `ISCC` compiling `script`; the script says where the setup program goes.
pub(super) fn command(iscc: &Path, script: &Path) -> Command {
    let mut cmd = Command::new(iscc);
    // `/Q`: only warnings and errors, not the whole compiler log.
    cmd.arg("/Q").arg(script);
    cmd
}

/// The script text.
pub(super) fn script(installer: &Installer) -> String {
    let name = directive(installer.app_name);
    let version = if installer.version.trim().is_empty() {
        "1.0.0"
    } else {
        installer.version.trim()
    };
    let mut setup = vec![
        // `{{` is how a script spells a literal `{`, so the id's opening brace.
        format!("AppId={{{{{}}}", installer.app_id),
        format!("AppName={name}"),
        format!("AppVersion={}", directive(version)),
        format!(
            "DefaultDirName={{autopf}}\\{}",
            directive(&folder_name(installer.app_name))
        ),
        "DisableProgramGroupPage=yes".to_string(),
        "PrivilegesRequired=lowest".to_string(),
        "PrivilegesRequiredOverridesAllowed=dialog".to_string(),
        format!("OutputDir={}", directive(&installer.dist.to_string_lossy())),
        format!("OutputBaseFilename={}", directive(installer.base_name)),
        format!(
            "UninstallDisplayIcon={{app}}\\{}",
            directive(installer.exe_name)
        ),
        "Compression=lzma2".to_string(),
        "SolidCompression=yes".to_string(),
        "WizardStyle=modern".to_string(),
    ];
    if !installer.publisher.trim().is_empty() {
        setup.push(format!(
            "AppPublisher={}",
            directive(installer.publisher.trim())
        ));
    }
    let icon = installer.bundle.join("app.ico");
    if icon.is_file() {
        setup.push(format!(
            "SetupIconFile={}",
            directive(&icon.to_string_lossy())
        ));
    }
    match installer.arch {
        "arm64" => {
            setup.push("ArchitecturesAllowed=arm64".to_string());
            setup.push("ArchitecturesInstallIn64BitMode=arm64".to_string());
        }
        "x64" => {
            setup.push("ArchitecturesAllowed=x64compatible".to_string());
            setup.push("ArchitecturesInstallIn64BitMode=x64compatible".to_string());
        }
        _ => {}
    }

    let app = format!("{{app}}\\{}", param(installer.exe_name));
    let mut lines = vec![
        "; Generated by `aimer package windows`; edits are lost on the next run.".to_string(),
        "[Setup]".to_string(),
    ];
    lines.extend(setup);
    lines.extend([
        String::new(),
        "[Files]".to_string(),
        format!(
            "Source: \"{}\\*\"; DestDir: \"{{app}}\"; Flags: ignoreversion recursesubdirs createallsubdirs",
            param(&installer.bundle.to_string_lossy())
        ),
        String::new(),
        "[Tasks]".to_string(),
        "Name: \"desktopicon\"; Description: \"{cm:CreateDesktopIcon}\"; \
         GroupDescription: \"{cm:AdditionalIcons}\"; Flags: unchecked"
            .to_string(),
        String::new(),
        "[Icons]".to_string(),
        format!(
            "Name: \"{{autoprograms}}\\{shortcut}\"; Filename: \"{app}\"",
            shortcut = param(&folder_name(installer.app_name)),
        ),
        format!(
            "Name: \"{{autodesktop}}\\{shortcut}\"; Filename: \"{app}\"; Tasks: desktopicon",
            shortcut = param(&folder_name(installer.app_name)),
        ),
        String::new(),
        "[Run]".to_string(),
        format!(
            "Filename: \"{app}\"; Description: \"Launch {}\"; Flags: nowait postinstall skipifsilent",
            param(installer.app_name)
        ),
    ]);
    lines.push(String::new());
    lines.join("\n")
}

/// A value of a `[Setup]` directive: `{` is the start of a constant, so a
/// literal one is doubled.
fn directive(value: &str) -> String {
    value.replace('{', "{{")
}

/// The text of a string parameter of a section line, for use between quotes:
/// `"` is doubled and `{` too, since both mean something to the compiler.
fn param(value: &str) -> String {
    value.replace('"', "\"\"").replace('{', "{{")
}

/// The application name as a folder name: the characters Windows forbids in one
/// are dropped.
fn folder_name(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .filter(|c| !matches!(c, '\\' | '/' | ':' | '*' | '?' | '"' | '<' | '>' | '|'))
        .collect();
    let cleaned = cleaned.trim().trim_end_matches('.').to_string();
    if cleaned.is_empty() {
        "App".to_string()
    } else {
        cleaned
    }
}

