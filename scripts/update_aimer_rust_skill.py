#!/usr/bin/env python3
"""Generate/check the Aimer Rust skill's tool list from MCP tools/list."""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys


BEGIN = "<!-- BEGIN GENERATED AIMER MCP TOOLS -->"
END = "<!-- END GENERATED AIMER MCP TOOLS -->"
TOOL_REFERENCE = re.compile(r"(?:Aimer MCP|MCP) tools? `([^`]+)`", re.IGNORECASE)
STALE_REFERENCE = re.compile(r"\b(?:aimer_rust_|mcp__aimer__)[a-zA-Z0-9_]+\b")


def receive_response(process, expected_id):
    while True:
        line = process.stdout.readline()
        if not line:
            raise RuntimeError("Aimer MCP server exited before replying")
        message = json.loads(line)
        if message.get("id") == expected_id:
            if "error" in message:
                raise RuntimeError(f"MCP request failed: {message['error']}")
            return message.get("result", {})


def server_tools(executable, project):
    process = subprocess.Popen(
        [executable, "mcp", "--project", str(project)],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
        encoding="utf-8",
        bufsize=1,
    )
    try:
        initialize = {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {
                "protocolVersion": "2025-03-26",
                "capabilities": {},
                "clientInfo": {"name": "aimer-skill-tool-list", "version": "1"},
            },
        }
        process.stdin.write(json.dumps(initialize) + "\n")
        process.stdin.flush()
        receive_response(process, 1)
        process.stdin.write(
            json.dumps({"jsonrpc": "2.0", "method": "notifications/initialized"}) + "\n"
        )
        process.stdin.write(
            json.dumps(
                {"jsonrpc": "2.0", "id": 2, "method": "tools/list", "params": {}}
            )
            + "\n"
        )
        process.stdin.flush()
        result = receive_response(process, 2)
        tools = result.get("tools", [])
        names = sorted({tool["name"] for tool in tools if isinstance(tool.get("name"), str)})
        if not names:
            raise RuntimeError("MCP tools/list returned no tools")
        return names
    finally:
        if process.stdin:
            process.stdin.close()
        process.terminate()
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()


def generated_region(names):
    body = "\n".join(f"- `{name}`" for name in names)
    return f"{BEGIN}\n<!-- Generated by scripts/update_aimer_rust_skill.py. -->\n{body}\n{END}"


def replace_region(document, replacement):
    if document.count(BEGIN) != 1 or document.count(END) != 1:
        raise RuntimeError("skill must contain exactly one generated tool-list marker pair")
    start = document.index(BEGIN)
    finish = document.index(END, start) + len(END)
    return document[:start] + replacement + document[finish:]


def validate_references(document, names):
    exposed = set(names)
    references = TOOL_REFERENCE.findall(document)
    unknown = sorted(set(references) - exposed)
    if unknown:
        raise RuntimeError("skill references MCP tool names not exposed by the server: " + ", ".join(unknown))
    stale = sorted(set(STALE_REFERENCE.findall(document)))
    if stale:
        raise RuntimeError("skill contains stale qualified MCP tool names: " + ", ".join(stale))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in skill is stale")
    parser.add_argument("--executable", default=os.environ.get("AIMER_BIN", "aimer"))
    parser.add_argument("--project", type=Path, help="workspace used to query the MCP server")
    args = parser.parse_args()

    repository = Path(__file__).resolve().parents[1]
    project = (args.project or repository).resolve()
    skill = repository / "aimer-rust" / "SKILL.md"
    names = server_tools(args.executable, project)
    current = skill.read_text(encoding="utf-8")
    validate_references(current, names)
    updated = replace_region(current, generated_region(names))
    if args.check:
        if updated != current:
            print("aimer-rust/SKILL.md tool list is stale; run scripts/update_aimer_rust_skill.py", file=sys.stderr)
            return 1
        return 0
    skill.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, RuntimeError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        raise SystemExit(1)
